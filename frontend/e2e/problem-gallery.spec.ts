import { expect, test } from '@playwright/test';

test('public problem gallery discovery and return navigation', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('http://127.0.0.1:3100/login');
  await page.getByLabel('Username or email').fill('learner@example.test');
  await page.getByLabel('Password', { exact: true }).fill('DemoPass123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.goto('http://127.0.0.1:3100/practice?scope=public');
  await expect(page.getByRole('heading', { name: 'Public catalog.' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Disjoint Interval Consolidation' })).toBeVisible();
  await page.screenshot({ path: '../docs/feature/problem-gallery-after.png' });
  await page.getByRole('button', { name: /02 Unweighted Grid Shortest Path/ }).click();
  await expect(page.getByRole('heading', { name: 'Unweighted Grid Shortest Path' })).toBeVisible();
  await page.getByRole('button', { name: 'Read full statement' }).click();
  await expect(page.getByRole('dialog', { name: /Full statement/ })).toBeVisible();
  await expect(page.getByRole('dialog').getByText('3 3\n0 0 1\n1 0 0\n1 0 0')).toBeVisible();
  await expect(page.getByRole('dialog').getByText('1 6\n8 10\n15 18')).toHaveCount(0);
  await page.screenshot({ path: '../docs/feature/problem-folio-after.png', animations: 'disabled' });
  await page.getByRole('dialog').getByRole('button', { name: 'Previous' }).click();
  await expect(page.getByRole('dialog', { name: /Disjoint Interval Consolidation/ })).toBeVisible();
  await expect(page.getByRole('dialog').getByText('1 6\n8 10\n15 18')).toBeVisible();
  await page.getByRole('dialog').getByRole('button', { name: 'Next' }).click();
  await expect(page.getByRole('dialog', { name: /Unweighted Grid Shortest Path/ })).toBeVisible();
  await page.getByRole('button', { name: 'Close full statement' }).click();
  await expect(page.getByRole('button', { name: 'Read full statement' })).toBeFocused();
  await page.getByRole('button', { name: 'Index', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Unweighted Grid Shortest Path' })).toBeVisible();
  await page.getByRole('button', { name: 'Gallery', exact: true }).click();
  await page.getByRole('link', { name: /Start solving/ }).first().click();
  await expect(page).toHaveURL(/\/practice\/problems\/pub-shortest-path/);
  await page.getByRole('link', { name: 'Public catalog' }).first().click();
  await expect(page).toHaveURL(/view=index|selected=pub-shortest-path|scope=public/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '../docs/feature/problem-gallery-mobile-after.png' });
  await page.getByRole('button', { name: 'Gallery', exact: true }).click();
  await page.getByRole('button', { name: 'Read full statement' }).click();
  await page.screenshot({ path: '../docs/feature/problem-folio-mobile-after.png', animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
});
